// Generates content/stages/*.json from scripts/stage-defs.ts. Run: npm run content
import { mkdirSync, writeFileSync } from 'node:fs';
import { TUNING } from '../src/core/tuning';
import { buildPattern, onsetsOf } from '../src/core/patterns';
import { validateStage } from '../src/core/schema';
import { LAYER_COLORS, type Creature, type Stage } from '../src/core/types';
import { shade } from './colors';
import { BODY_OF, LAYER_ORDER, STAGES } from './stage-defs';

export const LIGHTNESS = [-0.08, -0.02, 0.04, 0.1, -0.12, 0.15]; // six shades per layer
export const seedOf = (stageIdx: number, layerIdx: number, variant: number): number => 1000 * (stageIdx + 1) + 100 * layerIdx + variant;

export function buildStage(stageIdx: number): Stage {
  const d = STAGES[stageIdx]!;
  const stageBase = { chordLoop: d.chords, key: d.key };
  const creatures: Creature[] = [];
  LAYER_ORDER.forEach((layer, li) => {
    for (let v = 0; v < TUNING.perLayer; v++) {
      const id = `${d.id}_${layer}_${v + 1}`;
      const events = buildPattern({ stage: stageBase, layer, variant: v, seed: seedOf(stageIdx, li, v), swing: d.swing, world: stageIdx });
      creatures.push({
        id, layer, loopFile: `${id}.m4a`, onsets: onsetsOf(events),
        color: shade(LAYER_COLORS[layer], d.hueShift, LIGHTNESS[v]!),
        shape: { body: BODY_OF[layer], eyes: d.eyes[(v + li) % 4]!, species: d.species[(v + li) % 6]!, accessory: d.accessories[(v + li * 2) % 4]!, look: d.look },
      });
    }
  });
  const byLayer = (l: string) => creatures.filter((c) => c.layer === l);
  const combos = Array.from({ length: TUNING.combosPerStage }, (_, i) => ({
    id: `${d.id}_combo_${i + 1}`,
    creatureIds: [byLayer('drums')[i]!.id, byLayer('bass')[(i + 1) % TUNING.perLayer]!.id, byLayer('melody')[(i + 2) % TUNING.perLayer]!.id, byLayer('voice')[(i + 3) % TUNING.perLayer]!.id] as [string, string, string, string],
    bonusLoopFile: `${d.id}_bonus_${i + 1}.m4a`,
    celebrationId: `cel_${d.id}_${i + 1}`,
  }));
  return { id: d.id, nameKey: d.nameKey, bpm: d.bpm, key: d.key, timeSignature: '4/4', loopBars: 4, chordLoop: d.chords, palette: d.palette, ambienceFile: `${d.id}_ambience.m4a`, creatures, combos };
}

if (process.argv[1]?.endsWith('build-content.ts')) {
  mkdirSync('content/stages', { recursive: true });
  STAGES.forEach((d, i) => {
    const stage = buildStage(i);
    const { errors } = validateStage(stage);
    if (errors.length) throw new Error(`${d.id}: ${errors.join('; ')}`);
    writeFileSync(`content/stages/${i + 1}-${d.id}.json`, JSON.stringify(stage, null, 2) + '\n');
    console.log('wrote', d.id);
  });
  // Static require map for Metro (asset requires must be literal).
  const files: string[] = [];
  STAGES.forEach((_, i) => { const st = buildStage(i); st.creatures.forEach((c) => files.push(c.loopFile)); st.combos.forEach((c) => files.push(c.bonusLoopFile)); files.push(st.ambienceFile); });
  const lines = files.map((f) => `  '${f}': require('../../assets/loops/${f}'),`);
  writeFileSync('src/content/loopAssets.ts', `// GENERATED by scripts/build-content.ts — do not edit.\nexport const LOOP_ASSETS: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
}

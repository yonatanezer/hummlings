// Renders the interface icons (src/core/uiIcons.ts) and the world emblems (src/core/worldIcons.ts) once into PNGs, and writes src/ui/iconAssets.ts.
// The interface icons are white with transparency, so the app tints them. Run: npx tsx scripts/build-ui-icons.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { ICON_NAMES, ICON_SHAPES, type IconName } from '../src/core/uiIcons';
import { WORLD_ICONS } from '../src/core/worldIcons';
import { freshPaint, type Canvas, type SkiaApi, rect } from '../src/ui/draw/common';
import { renderPng } from './render-lib';

const SIZE = 192; // device pixels; the grid is 24 units, so one unit is 8 px
const K = SIZE / 24;
const STROKE = 1; // SkPaintStyle.Stroke

function round(sk: SkiaApi, paint: ReturnType<typeof freshPaint>) {
  // freshPaint already rounds the caps; joins are set here
  (paint as unknown as { setStrokeJoin(j: number): void }).setStrokeJoin(1); // StrokeJoin.Round
  void sk;
  return paint;
}

function drawIcon(sk: SkiaApi, c: Canvas, name: IconName) {
  c.scale(K, K);
  for (const s of ICON_SHAPES[name]) {
    if (s.kind === 'stroke') c.drawPath(sk.Path.MakeFromSVGString(s.d)!, round(sk, freshPaint(sk, '#FFFFFF', 1, STROKE, s.w ?? 2.2)));
    else if (s.kind === 'fill') c.drawPath(sk.Path.MakeFromSVGString(s.d)!, freshPaint(sk, '#FFFFFF'));
    else if (s.kind === 'circle') c.drawCircle(s.cx, s.cy, s.r, s.style === 'fill' ? freshPaint(sk, '#FFFFFF') : freshPaint(sk, '#FFFFFF', 1, STROKE, s.w ?? 2.2));
    else c.drawRRect(sk.RRectXY(rect(s.x, s.y, s.w, s.h), s.r, s.r), freshPaint(sk, '#FFFFFF'));
  }
}

function drawWorld(sk: SkiaApi, c: Canvas, id: string) {
  c.scale(K, K);
  for (const s of WORLD_ICONS[id]!) {
    const path = sk.Path.MakeFromSVGString(s.d)!;
    if (s.stroke) c.drawPath(path, round(sk, freshPaint(sk, s.stroke, 1, STROKE, s.width ?? 2)));
    else c.drawPath(path, freshPaint(sk, s.fill ?? '#FFFFFF'));
  }
}

async function main() {
  mkdirSync('assets/ui/icons', { recursive: true });
  const lines: string[] = ['// Generated by scripts/build-ui-icons.ts. Do not edit.', "import type { IconName } from '../core/uiIcons';", '', 'export const ICON_PNG: Record<IconName, number> = {'];
  for (const n of ICON_NAMES) {
    writeFileSync(`assets/ui/icons/${n}.png`, await renderPng(SIZE, SIZE, (sk, c) => drawIcon(sk, c, n)));
    lines.push(`  ${n}: require('../../assets/ui/icons/${n}.png'),`);
  }
  lines.push('};', '', 'export const WORLD_PNG: Record<string, number> = {');
  for (const id of Object.keys(WORLD_ICONS)) {
    writeFileSync(`assets/ui/icons/world_${id}.png`, await renderPng(SIZE, SIZE, (sk, c) => drawWorld(sk, c, id)));
    lines.push(`  ${id}: require('../../assets/ui/icons/world_${id}.png'),`);
  }
  lines.push('};', '');
  writeFileSync('src/ui/iconAssets.ts', lines.join('\n'));
  console.log(`${ICON_NAMES.length} icons, ${Object.keys(WORLD_ICONS).length} worlds`);
}
void main();
